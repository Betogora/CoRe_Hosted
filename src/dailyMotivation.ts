export function getDailyMotivation(now: string, options: LearningDayOptions = {}) {
  const day = getLearningDayKey(now, options);
  const index = day ? ((dayKeyIndex(day) % impulses.length) + impulses.length) % impulses.length : 0;
  return { day, text: impulses[index], mascotId: motifs[index % motifs.length] };
}
